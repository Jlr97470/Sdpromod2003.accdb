SELECT
  TBLSOCIETES.*,
  TBLSOCIETESQUESTIONNAIRES.*,
  TBLSOCIETESQUESTIONNAIRESTYPESID.*
FROM
  TBLSOCIETES
  INNER JOIN (
    TBLSOCIETESQUESTIONNAIRES
    INNER JOIN TBLSOCIETESQUESTIONNAIRESTYPESID ON TBLSOCIETESQUESTIONNAIRES.SocQstSocQstTypNum = TBLSOCIETESQUESTIONNAIRESTYPESID.SocQstTypIDSocQstTypNum
  ) ON TBLSOCIETES.SocNum = TBLSOCIETESQUESTIONNAIRES.SocQstSocNum;
