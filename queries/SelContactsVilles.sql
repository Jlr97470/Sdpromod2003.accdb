SELECT
  TBLCONTACTS.ConNum,
  TBLCONTACTS.ConSocNum,
  TBLCONTACTS.ConFonCode,
  TBLCONTACTS.ConCivCode,
  TBLCONTACTS.ConInscrit,
  TBLCONTACTS.ConDateMaj,
  TBLCONTACTS.ConDateCre,
  TBLCONTACTS.ConDateNai,
  TBLCONTACTS.ConLogin,
  TBLCONTACTS.ConPassword,
  TBLCONTACTS.ConNom,
  TBLCONTACTS.ConPrenom,
  TBLCONTACTS.ConAdresse,
  TBLVILLES.VilCodePostal AS ConVilCodePostal,
  TBLVILLES.VilNom AS ConVilNom,
  TBLCONTACTS.ConTelB,
  TBLCONTACTS.ConTelBLib,
  TBLCONTACTS.ConTelD,
  TBLCONTACTS.ConTelDLib,
  TBLCONTACTS.ConTelPort,
  TBLCONTACTS.ConFax,
  TBLCONTACTS.ConEMail,
  TBLCONTACTS.ConNotes,
  TBLCONTACTS.ConPerAdr,
  TBLVILLES_1.VilCodePostal AS ConPerVilCodePostal,
  TBLVILLES_1.VilNom AS ConPerVilNom,
  TBLCONTACTS.ConPerFax,
  TBLCONTACTS.ConPerTel,
  TBLCONTACTS.ConPerEMai
FROM
  TBLVILLES
  RIGHT JOIN (
    TBLCONTACTS
    LEFT JOIN TBLVILLES AS TBLVILLES_1 ON TBLCONTACTS.ConPerVilNum = TBLVILLES_1.VilNum
  ) ON TBLVILLES.VilNum = TBLCONTACTS.ConVilNum
ORDER BY
  TBLCONTACTS.ConNum;
