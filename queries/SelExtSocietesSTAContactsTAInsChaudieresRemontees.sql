SELECT
  TBLCHAUDIERESREMONTEES.ChdRemNum,
  TBLCHAUDIERESREMONTEES.ChdRemDate,
  TBLSOCIETES.SocRaison,
  TBLSOCIETES.SocAdresse,
  TBLVILLES.VilCodePostal AS SocVilCodePostal,
  TBLVILLES.VilNom AS SocVilNom,
  TBLSOCIETES.SocTel1,
  First(SelContactsInscrit.ConNom) AS ConNom,
  First(SelContactsInscrit.ConPrenom) AS ConPrenom,
  TBLCHAUDIERESREMONTEES.ChdRemSerie,
  TBLCHAUDIERESARTICLES.ChdArtRef,
  TBLCHAUDIERESARTICLES.ChdArtGamme,
  TBLCHAUDIERESARTICLES.ChdArtLibelle,
  TBLSEMESTRES.SemLibelle AS ChdSemLibelle,
  TBLCHAUDIERESREMONTEES.ChdRemSD,
  TBLCHAUDIERESREMONTEES.ChdRemServ,
  TBLCHAUDIERESREMONTEES.ChdRemRemp,
  TBLCHAUDIERESREMONTEES.ChdRemBene
FROM
  TBLVILLES
  RIGHT JOIN (
    (
      TBLSOCIETES
      LEFT JOIN SelContactsInscrit ON TBLSOCIETES.SocNum = SelContactsInscrit.ConSocNum
    )
    INNER JOIN (
      TBLSEMESTRES
      INNER JOIN (
        TBLCHAUDIERESARTICLES
        INNER JOIN TBLCHAUDIERESREMONTEES ON TBLCHAUDIERESARTICLES.ChdArtRef = TBLCHAUDIERESREMONTEES.ChdRemChdArtRef
      ) ON TBLSEMESTRES.SemNum = TBLCHAUDIERESREMONTEES.ChdRemSemNum
    ) ON TBLSOCIETES.SocNum = TBLCHAUDIERESREMONTEES.ChdRemSocNum
  ) ON TBLVILLES.VilNum = TBLSOCIETES.SocVilNum
GROUP BY
  TBLCHAUDIERESREMONTEES.ChdRemNum,
  TBLCHAUDIERESREMONTEES.ChdRemDate,
  TBLSOCIETES.SocRaison,
  TBLSOCIETES.SocAdresse,
  TBLVILLES.VilCodePostal,
  TBLVILLES.VilNom,
  TBLSOCIETES.SocTel1,
  TBLCHAUDIERESREMONTEES.ChdRemSerie,
  TBLCHAUDIERESARTICLES.ChdArtRef,
  TBLCHAUDIERESARTICLES.ChdArtGamme,
  TBLCHAUDIERESARTICLES.ChdArtLibelle,
  TBLSEMESTRES.SemLibelle,
  TBLCHAUDIERESREMONTEES.ChdRemSD,
  TBLCHAUDIERESREMONTEES.ChdRemServ,
  TBLCHAUDIERESREMONTEES.ChdRemRemp,
  TBLCHAUDIERESREMONTEES.ChdRemBene
ORDER BY
  TBLCHAUDIERESREMONTEES.ChdRemDate DESC;
